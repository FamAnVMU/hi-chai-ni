  /// Retrieves all items matching the specified skill.
  static List<CatItem> getItemsBySkill(CatSkill skill) {
    return defaultItems.where((item) => item.skill == skill).toList();
  }

  /// Finds item by its unique ID.
  static CatItem? getItemById(String id) {
    for (final item in defaultItems) {
      if (item.id == id) return item;
    }
    return null;
  }
